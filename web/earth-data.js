// 向东射线 + 奇偶判定
export function inPoly(lon, lat, poly) {
  var inside = false;
  for (var i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    var xi = poly[i][0], yi = poly[i][1];
    var xj = poly[j][0], yj = poly[j][1];
    if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export function isLand(lon, lat) {
  for (var i = 0; i < CONTINENTS.length; i++) {
    if (inPoly(lon, lat, CONTINENTS[i])) return true;
  }
  return false;
}

// 落在海里的点:由近及远逐圈找最近的陆地,偏移量 dist(度)一并返回,便于校验是否偏太多
export function snapToLand(lat, lon) {
  if (isLand(lon, lat)) return { lat: lat, lon: lon, snapped: false, dist: 0 };
  var kx = Math.max(0.35, Math.cos(lat * Math.PI / 180));   // 同样经度差在高纬更窄
  for (var r = 0.4; r <= 14; r += 0.4) {
    var steps = Math.max(10, Math.round(r * 14));
    for (var i = 0; i < steps; i++) {
      var a = i / steps * Math.PI * 2;
      var la = lat + Math.sin(a) * r;
      var lo = lon + Math.cos(a) * r / kx;
      if (la < -84 || la > 84) continue;
      if (lo > 180) lo -= 360; else if (lo < -180) lo += 360;
      if (isLand(lo, la)) return { lat: la, lon: lo, snapped: true, dist: r };
    }
  }
  return { lat: lat, lon: lon, snapped: false, dist: 0, failed: true };
}

// 网络层真正使用的落点:保证每个枢纽都在陆地上
export function landHubs() {
  return HUBS.map(function (h) {
    var p = snapToLand(h.lat, h.lon);
    return { c: h.c, lat: p.lat, lon: p.lon, snapped: p.snapped, dist: p.dist, failed: p.failed };
  });
}
